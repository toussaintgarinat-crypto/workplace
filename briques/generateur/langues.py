"""Configuration multilingue du générateur d'apps (S37).

Une app livrée est générée dans **une** langue, fixée à la livraison (une app = la
langue de l'entreprise cliente). Le français reste le défaut ET le repli : toute
langue inconnue retombe sur `fr`, et toute clé manquante dans une traduction
retombe sur sa valeur française (repli par clé — honnête : pas de texte vide).

Deux usages :
- `consigne_langue(langue)` : directive injectée dans les prompts LLM pour forcer la
  langue des VALEURS produites (le contenu sur-mesure : libellés, résumés, actions…).
- `textes(langue)` : dictionnaire des libellés STATIQUES du gabarit (le châssis :
  navigation, boutons CRUD, modal, messages JS), repris par `gabarit.py`.
"""

LANGUE_DEFAUT = "fr"

# code ISO 639-1 → nom lisible (pour instruire le LLM). 'ar' arrivera en S44 (RTL).
_NOMS = {
    "fr": "français",
    "en": "anglais (English)",
    "es": "espagnol (Español)",
    "ar": "arabe (العربية)",
}


def normaliser_langue(langue) -> str:
    """Ramène une entrée libre à un code supporté ; repli `fr` si inconnu."""
    code = (str(langue or "").strip().lower())[:2]
    return code if code in _NOMS else LANGUE_DEFAUT


def nom_langue(langue) -> str:
    return _NOMS[normaliser_langue(langue)]


def consigne_langue(langue) -> str:
    """Directive de langue de sortie à AJOUTER à un prompt LLM.

    Vide pour le français (comportement historique inchangé). Pour les autres
    langues : impose la langue des valeurs texte, en gardant les CLÉS JSON en
    français (elles sont structurelles, lues par le gabarit)."""
    code = normaliser_langue(langue)
    if code == "fr":
        return ""
    nom = _NOMS[code]
    return (
        f"\n\nLANGUE DE SORTIE — IMPÉRATIF : rédige TOUTES les valeurs de texte "
        f"(noms, libellés, titres, descriptions, résumés, messages, options de statut) "
        f"en {nom}. Garde les CLÉS du JSON strictement inchangées (en français, telles "
        f"que demandées). N'utilise aucune autre langue que {nom} dans les valeurs."
    )


