# 'ar' : ajouté en S44 (RTL). Pour l'instant il hérite entièrement du français par le
# repli de `textes()` (honnête : aucune fausse traduction).
_TABLE = {"fr": _FR, "en": _EN, "es": _ES}

# Sous-ensemble de clés exposées au JS embarqué (objet `T` côté navigateur) :
# tous les messages `js_*`, les préfixes du modal CRUD, et la locale de formatage.
_CLES_JS = ([k for k in _FR if k.startswith("js_")]
            + ["locale", "prefixe_nouveau", "prefixe_modifier"])


def textes(langue) -> dict:
    """Dictionnaire de libellés pour la langue demandée, avec repli par clé sur `fr`."""
    code = normaliser_langue(langue)
    if code == "fr":
        return dict(_FR)
    return {**_FR, **_TABLE.get(code, {})}


def textes_js(langue) -> dict:
    """Le sous-ensemble de libellés nécessaire au JS embarqué du gabarit."""
    t = textes(langue)
    return {k: t[k] for k in _CLES_JS}
